#include "3-calc.h"

/**
 * op_add - Add integers
 * @a: First integer
 * @b: Second integer
 *
 * Return: Addition of first and second integer
 */
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - Subtract integers
 * @a: First integer
 * @b: Second integer
 *
 * Return: Subtraction of first and second integer
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - Multiply integers
 * @a: First integer
 * @b: Second integer
 *
 * Return: Multiplication of first and second integer
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - Div integers
 * @a: First integer
 * @b: Second integer
 *
 * Return: Division of first and second integer
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - Get remainder of integers after division
 * @a: First integer
 * @b: Second integer
 *
 * Return: Remainder of integers after division
 */
int op_mod(int a, int b)
{
	return (a % b);
}
